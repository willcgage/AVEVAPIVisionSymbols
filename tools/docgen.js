#!/usr/bin/env node
/* ============================================================================
 * PVX docgen — generates docs/SYMBOL-REFERENCE.md from the symbols themselves.
 * ----------------------------------------------------------------------------
 * Each symbol's getDefaultConfig() is executed in a sandbox with a stub PVX and
 * PIVisualization, so the documented option list can never drift from the code.
 * Trailing `//` comments on config lines become the option descriptions.
 *
 *   node tools/docgen.js
 * ==========================================================================*/
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const SYMBOLS_DIR = path.join(ROOT, 'src', 'symbols');
const OUT = path.join(ROOT, 'docs', 'SYMBOL-REFERENCE.md');

/* --- the real core, so wrapped defaults and shared options are documented --
 * Stubs used to stand in for PVX here, and drifted: every symbol whose
 * getDefaultConfig() went through PVX.afsource.defaults or PVX.filter.defaults
 * threw against them and was published with an EMPTY option table (the Combo
 * Chart among them), and the shared options added since 1.8 were missing
 * everywhere. An assistant asked to configure a symbol from this reference
 * then had nothing to go on and invented options. pvx-core.js loads without
 * a DOM, so it is evaluated as it ships. */
const CORE = fs.readFileSync(path.join(ROOT, 'src', 'shared', 'pvx-core.js'), 'utf8');

function makeSandbox() {
    const registered = [];
    const PV = {
        Extensibility: { Enums: { DatasourceBehaviors: { None: 'None', Single: 'Single', Multiple: 'Multiple' } } },
        deriveVisualizationFromBase: (c) => { c.prototype = c.prototype || {}; return c; },
        symbolCatalog: { register: (d) => registered.push(d) }
    };
    const win = { PIVisualization: PV, console, setTimeout, clearTimeout };
    win.window = win;
    const sandbox = vm.createContext(win);
    vm.runInContext(CORE, sandbox, { filename: 'pvx-core.js', timeout: 4000 });
    // Capture the definition before registration wires the lifecycle up.
    win.PVX.register = (pv, def) => { registered.push(def); };
    return { sandbox, registered };
}

/** Trailing `// comment` on the line that declares each config key. */
function commentsFor(js) {
    const map = {};
    js.split('\n').forEach((line) => {
        const m = /^\s*([A-Za-z][A-Za-z0-9_]*)\s*:\s*.+?\/\/\s*(.+?)\s*$/.exec(line);
        if (m) { map[m[1]] = m[2]; }
    });
    return map;
}

function headerDoc(js) {
    const m = /^\/\*[\s\S]*?\*\//.exec(js);
    if (!m) { return ''; }
    return m[0]
        .replace(/^\/\*+|\*+\/$/g, '')
        .split('\n')
        .map((l) => l.replace(/^\s*\*?\s?/, '').replace(/^=+$/, '').replace(/^-+$/, ''))
        .join('\n')
        .trim();
}

// Whatever PVX.config.base() gives every symbol, read from the core itself.
const INHERITED = (function () {
    const { sandbox } = makeSandbox();
    return Object.keys(vm.runInContext('PVX.config.base({})', sandbox));
}());

function fmtValue(v) {
    if (v === '') { return '`""`'; }
    if (Array.isArray(v)) { return '`' + JSON.stringify(v) + '`'; }
    if (typeof v === 'string' && v.length > 46) { return '`' + v.slice(0, 44) + '…`'; }
    return '`' + JSON.stringify(v) + '`';
}

function main() {
    const dirs = fs.readdirSync(SYMBOLS_DIR)
        .filter((d) => fs.statSync(path.join(SYMBOLS_DIR, d)).isDirectory())
        .sort();

    const out = [];
    out.push('# PVX symbol reference');
    out.push('');
    out.push('> Generated by `node tools/docgen.js` from the symbol sources. Do not edit by hand.');
    out.push('');
    out.push('Each table below is the complete list of a symbol\'s options, read from the code');
    out.push('that ships. An option that is not in a symbol\'s table does not exist, whatever a');
    out.push('description or a suggested design implies; the Format pane shows the same options');
    out.push('under readable labels. When an assistant drafts a display from these symbols, give');
    out.push('it this file and ask it to name the option behind each feature it proposes.');
    out.push('');
    out.push('Every symbol inherits a shared set of options from `PVX.config.base()`:');
    out.push('`' + INHERITED.join('`, `') + '`. Those are listed once here and marked');
    out.push('*(shared)* in each table.');
    out.push('');
    out.push('| Symbol | Display name | Data shape | Data sources |');
    out.push('|---|---|---|---|');

    const collected = [];
    dirs.forEach((typeName) => {
        const js = fs.readFileSync(path.join(SYMBOLS_DIR, typeName, 'symbol.js'), 'utf8');
        const { sandbox, registered } = makeSandbox();
        try {
            vm.runInContext(js, sandbox, { filename: typeName + '/symbol.js', timeout: 4000 });
        } catch (e) {
            console.error('could not evaluate ' + typeName + ': ' + e.message);
            return;
        }
        const def = registered[0];
        if (!def) { console.error('no definition registered by ' + typeName); return; }

        let cfg = {};
        try {
            cfg = def.getDefaultConfig ? def.getDefaultConfig() : {};
        } catch (e) {
            // An empty table reads as "this symbol has no options"; refuse.
            console.error('getDefaultConfig() failed for ' + typeName + ': ' + e.message);
            process.exitCode = 1;
            return;
        }

        collected.push({
            typeName,
            displayName: def.displayName || typeName,
            shape: cfg.DataShape || '—',
            behavior: def.datasourceBehavior || 'None',
            supportsCollections: !!def.supportsCollections,
            cfg,
            comments: commentsFor(js),
            doc: headerDoc(js)
        });

        out.push('| [`' + typeName + '`](#' + typeName.toLowerCase() + ') | ' + (def.displayName || typeName) +
            ' | ' + (cfg.DataShape || '—') + ' | ' + (def.datasourceBehavior || 'None') + ' |');
    });

    out.push('');

    collected.forEach((s) => {
        out.push('---');
        out.push('');
        out.push('## ' + s.typeName);
        out.push('');
        out.push('**' + s.displayName + '** · data shape `' + s.shape + '` · ' +
            s.behavior.toLowerCase() + ' data source' + (s.behavior === 'Multiple' ? 's' : '') +
            ' · collections ' + (s.supportsCollections ? 'supported' : 'not supported'));
        out.push('');

        // The first paragraph of the file header is the symbol's purpose.
        const lines = s.doc.split('\n');
        const start = lines.findIndex((l) => l.trim() && !l.startsWith(s.typeName));
        const blurb = [];
        for (let i = Math.max(0, start); i < lines.length; i++) {
            const l = lines[i].trim();
            if (!l && blurb.length) { break; }
            // "@mock x" lines are harness directives, not prose.
            if (l && !/^DataShape:/.test(l) && !/^@/.test(l)) { blurb.push(l); }
        }
        if (blurb.length) { out.push(blurb.join(' ')); out.push(''); }

        out.push('| Option | Default | Notes |');
        out.push('|---|---|---|');
        Object.keys(s.cfg).forEach((k) => {
            if (k === 'DataShape' || k === 'Height' || k === 'Width') { return; }
            const note = s.comments[k] || (INHERITED.indexOf(k) !== -1 ? '*(shared)*' : '');
            out.push('| `' + k + '` | ' + fmtValue(s.cfg[k]) + ' | ' + note.replace(/\|/g, '\\|') + ' |');
        });
        out.push('');
    });

    out.push('---');
    out.push('');
    out.push('## Threshold syntax');
    out.push('');
    out.push('Every symbol that colors by limits uses the same string:');
    out.push('');
    out.push('```');
    out.push('0:#2f9e5f:Normal, 70:#d99024:High, 90:#c8452f:Critical');
    out.push('```');
    out.push('');
    out.push('Each entry is `lowerLimit:color:label`, comma separated. A band applies from');
    out.push('its own limit up to the next band\'s limit; the last band runs to the top of');
    out.push('the scale. Values below the first limit match no band and fall back to the');
    out.push('symbol\'s accent color. The label is optional and is what symbols show when');
    out.push('"show band label" is switched on.');
    out.push('');
    out.push('The string above is a placeholder on a 0-100 scale, and most symbols start');
    out.push('with it. The three that raise alarms (Exception Banner, Annunciator, Status');
    out.push('Grid) start with no bands, and with no bands they flag nothing and say that');
    out.push('no limits are set. A display saved by 1.9.0 or earlier with the placeholder');
    out.push('on one of those three loads with no bands. They read only these bands, not');
    out.push('the limits configured on an AF attribute.');
    out.push('');

    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, out.join('\n'), 'utf8');
    console.log('wrote ' + path.relative(ROOT, OUT) + '  (' + collected.length + ' symbols)');
}

main();
